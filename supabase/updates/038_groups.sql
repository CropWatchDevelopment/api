-- 038_groups.sql
-- Device and location groups become records instead of free text.
--
-- Until now a group was whatever string a user typed into cw_devices."group" or
-- cw_locations."group". This adds one table per pool (devices and locations
-- are separate pools) and a group_id on each resource:
--
--   cw_location_groups      one row per location group: org, name, creator.
--   cw_device_groups        one row per device group: org, name, creator.
--   cw_locations.group_id   the location's group; NULL = none.
--   cw_devices.group_id     the device's group; NULL = none.
--
-- A group belongs to an ORGANIZATION: one group per name per org, used by the
-- org's locations (or devices). The API shows a user the groups on the
-- locations/devices they can access (all of the org's groups to its owner
-- and managers, every group to staff) plus the unused groups they created.
-- The creator (while they can still see the group), the org's owner and
-- managers, and staff rename or delete a group. Deleting a group clears it on
-- every resource that uses it (ON DELETE SET NULL); deleting the creator's
-- account keeps the group, with no creator.
--
-- The API's interface does not change: every endpoint still reads and writes
-- `group` as a string, and the API maps it to the group of that name in the
-- resource's org. The old text columns stay until 039 drops them, after the
-- new API is live.
--
-- Backfill: one group per (resource org, trimmed name), credited to the owner
-- of the org's lowest-id resource with that name, then group_id on every row
-- whose text is not blank. Prod as simulated read-only on 2026-11-22:
-- locations 46 rows → 18 groups, devices 20 rows → 7 groups.
--
-- Transition bridge (dropped by 039): while the CURRENTLY DEPLOYED API still
-- writes the text column, a trigger turns each such write into the org's
-- group of that name, so rows edited between this script and the new API's
-- deploy keep a correct group_id. The new API never writes the text column,
-- so the trigger then has nothing to do. Its name sorts after the org_fill_*
-- triggers on purpose: it must see the org they fill in.
--
-- Run this IMMEDIATELY before deploying the new API: until that deploy, the
-- old API returns raw rows, so its responses carry the extra group_id key.
--
-- Rolling the API back after the new API went live (and before 039): the new
-- API does not write the text columns, so they go stale. Run the API ROLLBACK
-- block at the bottom before redeploying the old API.
--
-- Additive and re-runnable (IF NOT EXISTS / OR REPLACE; the backfill runs on
-- the first run only). Once the new API is live the text columns go stale, so
-- the final check aborts a re-run, which then changes nothing.
-- The new tables are service-role only (RLS on, anon/authenticated revoked).
-- Patch database.types.ts (api + CropWatch) after. OPS check and rollbacks at
-- the bottom.

BEGIN;

-- Fail fast instead of queueing behind a long read on cw_devices / cw_locations.
SET LOCAL lock_timeout = '5s';

-- Take both table locks first, in the order the API's reads take them
-- (devices, then their locations), so this script cannot deadlock with a
-- request that holds one table and waits for the other.
LOCK TABLE public.cw_devices, public.cw_locations IN ACCESS EXCLUSIVE MODE;

-- Backfill only on the first run: once the new API is live the text columns
-- are stale, and re-linking from them would undo the API's changes.
CREATE TEMP TABLE _038_run ON COMMIT DROP AS
SELECT to_regclass('public.cw_location_groups') IS NULL AS first_run;

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

-- Names: the API trims them; the check keeps stray leading/trailing spaces out
-- of hand-written rows too. No upper bound: the API keeps enforcing its old
-- limits (device groups 120 characters, counted the way its validators count
-- them, emoji included; location groups none), so no request that works
-- today starts failing.
-- UNIQUE NULLS NOT DISTINCT (org_id, name): one group per name per org (a
-- resource without an org shares the org-less group of that name).
CREATE TABLE IF NOT EXISTS public.cw_location_groups (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id      uuid REFERENCES public.organizations (id) ON DELETE CASCADE,
    name        text NOT NULL
                CONSTRAINT cw_location_groups_name_format
                CHECK (char_length(name) >= 1 AND name !~ '^\s|\s$'),
    created_by  uuid REFERENCES public.profiles (id) ON DELETE SET NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT cw_location_groups_org_name_key UNIQUE NULLS NOT DISTINCT (org_id, name)
);

CREATE TABLE IF NOT EXISTS public.cw_device_groups (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id      uuid REFERENCES public.organizations (id) ON DELETE CASCADE,
    name        text NOT NULL
                CONSTRAINT cw_device_groups_name_format
                CHECK (char_length(name) >= 1 AND name !~ '^\s|\s$'),
    created_by  uuid REFERENCES public.profiles (id) ON DELETE SET NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT cw_device_groups_org_name_key UNIQUE NULLS NOT DISTINCT (org_id, name)
);

ALTER TABLE public.cw_location_groups ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.cw_location_groups FROM anon, authenticated;
ALTER TABLE public.cw_device_groups ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.cw_device_groups FROM anon, authenticated;

ALTER TABLE public.cw_locations
    ADD COLUMN IF NOT EXISTS group_id bigint REFERENCES public.cw_location_groups (id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS cw_locations_group_id_idx ON public.cw_locations (group_id);

ALTER TABLE public.cw_devices
    ADD COLUMN IF NOT EXISTS group_id bigint REFERENCES public.cw_device_groups (id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS cw_devices_group_id_idx ON public.cw_devices (group_id);

-- Finds "the groups this user created" (unused groups in the list).
CREATE INDEX IF NOT EXISTS cw_location_groups_created_by_idx ON public.cw_location_groups (created_by);
CREATE INDEX IF NOT EXISTS cw_device_groups_created_by_idx ON public.cw_device_groups (created_by);

COMMENT ON TABLE public.cw_location_groups IS
    'Location groups (sidebar filter, settings dropdown), one per name per org. Visible to anyone who can access a location using it, the org''s owner/managers, staff, and the creator while unused.';
COMMENT ON TABLE public.cw_device_groups IS
    'Device groups (settings dropdown, dashboard filter), one per name per org. Visible to anyone who can access a device using it, the org''s owner/managers, staff, and the creator while unused.';
COMMENT ON COLUMN public.cw_location_groups.created_by IS
    'Who created the group; they may rename or delete it while they can see it. NULL once that account is deleted.';
COMMENT ON COLUMN public.cw_device_groups.created_by IS
    'Who created the group; they may rename or delete it while they can see it. NULL once that account is deleted.';
COMMENT ON COLUMN public.cw_locations.group_id IS 'The location''s group (cw_location_groups); NULL = none. The API returns its name as `group`.';
COMMENT ON COLUMN public.cw_devices.group_id IS 'The device''s group (cw_device_groups); NULL = none. The API returns its name as `group`.';

-- ---------------------------------------------------------------------------
-- Transition helpers (dropped by 039)
-- ---------------------------------------------------------------------------

-- The group name a legacy text value stands for: trimmed (ASCII and
-- full-width spaces, like the API's String.trim), NULL when blank. (Callers
-- pass a cap far above any real name: nothing is cut.)
CREATE OR REPLACE FUNCTION public.cw_group_text_name(raw text, max_len integer)
RETURNS text
LANGUAGE sql
IMMUTABLE
SET search_path = public
AS $$
    SELECT nullif(
        regexp_replace(
            left(regexp_replace(coalesce(raw, ''), '^[\s　 ﻿]+|[\s　 ﻿]+$', '', 'g'), max_len),
            '[\s　 ﻿]+$', '', 'g'),
        '')
$$;

-- Old-API writes of cw_locations."group" → the org's location group of that name.
CREATE OR REPLACE FUNCTION public.cw_location_group_text_bridge()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    v_name text;
BEGIN
    IF TG_OP = 'UPDATE'
       AND NEW."group" IS NOT DISTINCT FROM OLD."group"
       AND NEW.org_id IS NOT DISTINCT FROM OLD.org_id THEN
        RETURN NEW;
    END IF;
    v_name := public.cw_group_text_name(NEW."group", 100000);
    IF v_name IS NULL THEN
        -- A cleared text clears the group; an insert without text keeps
        -- whatever group_id the writer set.
        IF TG_OP = 'UPDATE' THEN
            NEW.group_id := NULL;
        END IF;
        RETURN NEW;
    END IF;
    INSERT INTO public.cw_location_groups (org_id, name, created_by)
    VALUES (NEW.org_id, v_name, (SELECT p.id FROM public.profiles p WHERE p.id = NEW.owner_id))
    ON CONFLICT (org_id, name) DO NOTHING;
    SELECT g.id INTO NEW.group_id
    FROM public.cw_location_groups g
    WHERE g.org_id IS NOT DISTINCT FROM NEW.org_id AND g.name = v_name;
    RETURN NEW;
END
$$;

-- Old-API writes of cw_devices."group" → the org's device group of that name.
-- (A device's org follows its location: org_fill_device_org sets it first.)
CREATE OR REPLACE FUNCTION public.cw_device_group_text_bridge()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    v_name text;
BEGIN
    IF TG_OP = 'UPDATE'
       AND NEW."group" IS NOT DISTINCT FROM OLD."group"
       AND NEW.org_id IS NOT DISTINCT FROM OLD.org_id THEN
        RETURN NEW;
    END IF;
    v_name := public.cw_group_text_name(NEW."group", 100000);
    IF v_name IS NULL THEN
        IF TG_OP = 'UPDATE' THEN
            NEW.group_id := NULL;
        END IF;
        RETURN NEW;
    END IF;
    INSERT INTO public.cw_device_groups (org_id, name, created_by)
    VALUES (NEW.org_id, v_name, (SELECT p.id FROM public.profiles p WHERE p.id = NEW.user_id))
    ON CONFLICT (org_id, name) DO NOTHING;
    SELECT g.id INTO NEW.group_id
    FROM public.cw_device_groups g
    WHERE g.org_id IS NOT DISTINCT FROM NEW.org_id AND g.name = v_name;
    RETURN NEW;
END
$$;

REVOKE ALL ON FUNCTION public.cw_group_text_name(text, integer) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.cw_location_group_text_bridge() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.cw_device_group_text_bridge() FROM PUBLIC, anon, authenticated;

-- Fires only when a writer names the text column (UPDATE OF "group") or
-- inserts a row, so the new API's group_id-only writes pass through untouched.
-- BEFORE triggers run in name order: "sync_…" runs after "org_fill_…", so
-- NEW.org_id is final here.
DROP TRIGGER IF EXISTS sync_group_from_text ON public.cw_locations;
CREATE TRIGGER sync_group_from_text
    BEFORE INSERT OR UPDATE OF "group" ON public.cw_locations
    FOR EACH ROW EXECUTE FUNCTION public.cw_location_group_text_bridge();

DROP TRIGGER IF EXISTS sync_group_from_text ON public.cw_devices;
CREATE TRIGGER sync_group_from_text
    BEFORE INSERT OR UPDATE OF "group" ON public.cw_devices
    FOR EACH ROW EXECUTE FUNCTION public.cw_device_group_text_bridge();

-- ---------------------------------------------------------------------------
-- Backfill (first run only — see _038_run above; a re-run only re-checks)
-- ---------------------------------------------------------------------------

DO $$
BEGIN
    IF NOT (SELECT first_run FROM _038_run) THEN
        RAISE NOTICE '038: already applied, backfill skipped';
        RETURN;
    END IF;

    -- One group per (org, name), credited to the owner of the org's
    -- lowest-id location with that name.
    INSERT INTO public.cw_location_groups (org_id, name, created_by)
    SELECT DISTINCT ON (l.org_id, n.name) l.org_id, n.name, p.id
    FROM public.cw_locations l
    CROSS JOIN LATERAL (SELECT public.cw_group_text_name(l."group", 100000) AS name) n
    LEFT JOIN public.profiles p ON p.id = l.owner_id
    WHERE l.group_id IS NULL AND n.name IS NOT NULL
    ORDER BY l.org_id, n.name, l.location_id
    ON CONFLICT (org_id, name) DO NOTHING;

    UPDATE public.cw_locations l
    SET group_id = g.id
    FROM public.cw_location_groups g
    WHERE l.group_id IS NULL
      AND g.org_id IS NOT DISTINCT FROM l.org_id
      AND g.name = public.cw_group_text_name(l."group", 100000);

    INSERT INTO public.cw_device_groups (org_id, name, created_by)
    SELECT DISTINCT ON (d.org_id, n.name) d.org_id, n.name, p.id
    FROM public.cw_devices d
    CROSS JOIN LATERAL (SELECT public.cw_group_text_name(d."group", 100000) AS name) n
    LEFT JOIN public.profiles p ON p.id = d.user_id
    WHERE d.group_id IS NULL AND n.name IS NOT NULL
    ORDER BY d.org_id, n.name, d.dev_eui
    ON CONFLICT (org_id, name) DO NOTHING;

    UPDATE public.cw_devices d
    SET group_id = g.id
    FROM public.cw_device_groups g
    WHERE d.group_id IS NULL
      AND g.org_id IS NOT DISTINCT FROM d.org_id
      AND g.name = public.cw_group_text_name(d."group", 100000);
END
$$;

-- Abort the whole script if any row's group does not match its text, or sits
-- in another org. On a re-run after the new API went live the text is stale,
-- so this aborts too: 038 is already applied then and there is nothing to do.
DO $$
DECLARE
    v_locations integer;
    v_devices   integer;
BEGIN
    SELECT count(*) INTO v_locations
    FROM public.cw_locations l
    LEFT JOIN public.cw_location_groups g ON g.id = l.group_id
    WHERE public.cw_group_text_name(l."group", 100000) IS DISTINCT FROM g.name
       OR (g.id IS NOT NULL AND g.org_id IS DISTINCT FROM l.org_id);

    SELECT count(*) INTO v_devices
    FROM public.cw_devices d
    LEFT JOIN public.cw_device_groups g ON g.id = d.group_id
    WHERE public.cw_group_text_name(d."group", 100000) IS DISTINCT FROM g.name
       OR (g.id IS NOT NULL AND g.org_id IS DISTINCT FROM d.org_id);

    IF v_locations > 0 OR v_devices > 0 THEN
        RAISE EXCEPTION '038: % location(s) and % device(s) have a group that does not match their text and org (expected only when re-run after the new API went live: 038 is applied, nothing to do)', v_locations, v_devices;
    END IF;
END
$$;

-- Let PostgREST (the API's Supabase client) see the new tables and relationships now.
NOTIFY pgrst, 'reload schema';

COMMIT;

