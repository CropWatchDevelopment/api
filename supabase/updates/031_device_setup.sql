-- 031_device_setup.sql
-- =============================================================================
-- Device setup v2: automatic TTI registration from the app.
--
--  A) cw_locations.network_region — the TTI cluster a location's devices are
--     registered on. Every location today is in Japan, so the column defaults
--     to 'as1'; staff change it for a location elsewhere.
--  B) cw_network_profiles — per device type and region: the TTI application
--     a new device is created in and its LoRaWAN settings. Seeded below from
--     the Data-Ingress subscriptions; VERIFY every seed row (frequency plan and
--     MAC/PHY versions) against an existing device in the TTI console before
--     go-live.
--  C) cw_device_inventory — staff-provisioned join keys, looked up by DevEUI.
--     AppKeys are AES-256-GCM encrypted by the API with the DevEUI as
--     associated data (never stored in clear, never returned). A row is only
--     usable by the organization it is reserved for (org_id) or by staff; a
--     row reserved for another organization blocks setup entirely, so a
--     shipped device cannot be claimed by someone who guessed its DevEUI.
--     Service role only.
--  D) cw_devices.tti_application_id — the application a device actually
--     lives in (created or adopted by the setup flow).
--  E) cw_devices.dev_eui format — 16 upper-case hex characters, so a
--     different spelling of one EUI can never become a second device.
--     (Every existing row already complies; checked 2026-10-11.)
--
-- Additive and idempotent: safe to run again. The first version (without
-- the inventory org_id and the DevEUI CHECK) ran in prod on 2026-10-11 —
-- run this version once more BEFORE deploying the device-setup API.
-- Patch database.types.ts (api + CropWatch) after.
-- =============================================================================

BEGIN;

-- A) location network region ------------------------------------------------------
ALTER TABLE public.cw_locations
  ADD COLUMN IF NOT EXISTS network_region text NOT NULL DEFAULT 'as1';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'cw_locations_network_region_check'
  ) THEN
    ALTER TABLE public.cw_locations
      ADD CONSTRAINT cw_locations_network_region_check
      CHECK (network_region IN ('as1', 'au1', 'eu1', 'nam1'));
  END IF;
END $$;

COMMENT ON COLUMN public.cw_locations.network_region IS
  'TTI cluster new devices at this location are registered on (031).';

-- B) network profiles ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.cw_network_profiles (
  id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_type_id       bigint NOT NULL REFERENCES public.cw_device_type (id) ON DELETE CASCADE,
  region               text   NOT NULL CHECK (region IN ('as1', 'au1', 'eu1', 'nam1')),
  application_id       text   NOT NULL CHECK (application_id ~ '^[a-z0-9](?:[-]?[a-z0-9]){2,}$'),
  frequency_plan_id    text   NOT NULL,
  lorawan_version      text   NOT NULL DEFAULT 'MAC_V1_0_3',
  lorawan_phy_version  text   NOT NULL DEFAULT 'PHY_V1_0_3_REV_A',
  supports_class_c     boolean NOT NULL DEFAULT false,
  default_join_eui     text   CHECK (default_join_eui IS NULL OR default_join_eui ~ '^[0-9A-F]{16}$'),
  is_active            boolean NOT NULL DEFAULT true,
  created_at           timestamptz NOT NULL DEFAULT now(),
  UNIQUE (device_type_id, region)
);

ALTER TABLE public.cw_network_profiles ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.cw_network_profiles FROM anon, authenticated;

-- Seeds: TTI apps Data-Ingress subscribes to. VERIFY before go-live.
INSERT INTO public.cw_network_profiles
  (device_type_id, region, application_id, frequency_plan_id)
VALUES
  -- as1 (Japan, AS923-1 with LBT)
  ( 2, 'as1', 'cw-jp-air-th',            'AS_920_923_LBT'),
  ( 6, 'as1', 'seeed-jp-sensecap-s2103', 'AS_920_923_LBT'),
  ( 7, 'as1', 'cw-jp-ss',                'AS_920_923_LBT'),
  ( 8, 'as1', 'seeed-jp-sensecap-s2120', 'AS_920_923_LBT'),
  (10, 'as1', 'netvox-ra02a',            'AS_920_923_LBT'),
  (17, 'as1', 'cw-jp-ss',                'AS_920_923_LBT'),
  (20, 'as1', 'dragino-ja-lt-22222',     'AS_920_923_LBT'),
  -- au1
  ( 1, 'au1', 'co2',                     'AU_915_928_FSB_2'),
  ( 2, 'au1', 'cw-air-th',               'AU_915_928_FSB_2'),
  ( 6, 'au1', 'seeed-sensecap-s2103',    'AU_915_928_FSB_2'),
  ( 8, 'au1', 'seeed-sensecap-s2120',    'AU_915_928_FSB_2'),
  (17, 'au1', 'cw-ss',                   'AU_915_928_FSB_2')
ON CONFLICT (device_type_id, region) DO NOTHING;

-- Relays are always Class C, and the only Class C devices (a relay is a type
-- that stores cw_relay_data). The API applies the same rule when it registers
-- a device; this keeps the rows consistent with it.
UPDATE public.cw_network_profiles p
   SET supports_class_c = (t.data_table_v2 = 'cw_relay_data')
  FROM public.cw_device_type t
 WHERE t.id = p.device_type_id
   AND p.supports_class_c IS DISTINCT FROM (t.data_table_v2 = 'cw_relay_data');

-- C) key inventory ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.cw_device_inventory (
  dev_eui         text PRIMARY KEY CHECK (dev_eui ~ '^[0-9A-F]{16}$'),
  device_type_id  bigint REFERENCES public.cw_device_type (id) ON DELETE SET NULL,
  join_eui        text NOT NULL CHECK (join_eui ~ '^[0-9A-F]{16}$'),
  -- 'v1:<iv b64>:<ciphertext+tag b64>' (AES-256-GCM, key in the API env)
  app_key_enc     text NOT NULL,
  -- the organization this device was shipped to; NULL = still in stock
  org_id          uuid REFERENCES public.organizations (id) ON DELETE SET NULL,
  note            text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  claimed_at      timestamptz,
  claimed_by      uuid
);

-- Added after the first version of this script ran in prod (2026-10-11):
-- re-running the script adds it to the existing table.
ALTER TABLE public.cw_device_inventory
  ADD COLUMN IF NOT EXISTS org_id uuid REFERENCES public.organizations (id) ON DELETE SET NULL;

ALTER TABLE public.cw_device_inventory ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.cw_device_inventory FROM anon, authenticated;

-- D) device's actual TTI application -------------------------------------------------
ALTER TABLE public.cw_devices
  ADD COLUMN IF NOT EXISTS tti_application_id text;

COMMENT ON COLUMN public.cw_devices.tti_application_id IS
  'TTI application the device lives in, set by device setup (031). Must be one of the applications of its device type.';

-- E) DevEUI format ------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'cw_devices_dev_eui_format'
  ) THEN
    ALTER TABLE public.cw_devices
      ADD CONSTRAINT cw_devices_dev_eui_format
      CHECK (dev_eui ~ '^[0-9A-F]{16}$');
  END IF;
END $$;

COMMIT;

